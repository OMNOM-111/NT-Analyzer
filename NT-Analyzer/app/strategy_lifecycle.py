"""Strategy lifecycle model — pure, testable transforms.

The Strategy Profiles registry historically used a free ``status`` field with a
mix of readiness states (``ready``/``in_progress``/``rejected``/``archived`` …).
This module formalizes a single 4-state *lifecycle* on top of that field so the
UI and portfolio logic can reason about one canonical dimension:

  1. ``trial``           — Испытание. Strategy under evaluation; reserves a
                           portfolio cell with a remaining-term note. Every
                           trial carries an individual ``trial_plan`` (time /
                           condition / effort / gates) decided at planning time.
  2. ``approved_demo``   — Утверждено для демо. Counts in the portfolio. Carries
                           a ``demo_plan`` (forecast + horizon) and a live↔history
                           reconciliation.
  3. ``approved_live``   — Утверждено для реальной торговли. Only reachable after
                           a profitable demo period.
  4. ``failed_archived`` — Провалено → Архив. Removed from NinjaTrader (AI
                           sandbox auto-quarantine; production flag + checklist +
                           deletion) and written to a do-not-recreate registry
                           keyed by a stable fingerprint.

A second orthogonal dimension is ``origin``: ``production`` (hand-developed) vs
``ai_lab`` (generated by the local LM Studio AI lab). The UI shows an "AI / LM
Studio" badge and keeps the two streams visually separate.

No IO here. Runtime/registry reads live in jobqueue/server so these functions
stay unit-testable in tests/test_strategy_lifecycle.py.
"""
from __future__ import annotations

import hashlib
import json
import re
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional, Tuple


